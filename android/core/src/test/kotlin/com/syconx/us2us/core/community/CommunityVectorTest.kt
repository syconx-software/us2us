package com.syconx.us2us.core.community

import com.google.protobuf.ByteString
import com.syconx.us2us.core.AccountId
import com.syconx.us2us.core.encoding.Base64Url
import com.syconx.us2us.core.encoding.Hex
import com.syconx.us2us.core.proto.Content
import com.syconx.us2us.core.proto.communityMessage
import com.syconx.us2us.core.proto.content
import com.syconx.us2us.core.testing.deterministicIdentity
import kotlinx.serialization.json.*
import org.junit.jupiter.api.Assertions.*
import org.junit.jupiter.api.Test
import java.io.File

class CommunityVectorTest {
    private val prettyJson = Json { prettyPrint = true }
    private fun fixture() = File(System.getProperty("us2us.specDir"), "test-vectors/communities.json")
    private val owner = deterministicIdentity(71)
    private val member = deterministicIdentity(72)
    private val ownerId = AccountId.parse("00000000-0000-4000-8000-000000000001")
    private val memberId = AccountId.parse("00000000-0000-4000-8000-000000000002")
    private val groupId = AccountId.parse("11111111-2222-4333-8444-555555555555")
    private val key = Base64Url.encode(owner.publicKey.serialize())
    private fun state() = CommunityState(groupId, 2, "public", ownerId, key, "Us2us Türkçe", listOf(
        CommunityMember(ownerId, key), CommunityMember(memberId, Base64Url.encode(member.publicKey.serialize())),
    ))
    private fun message() = content { community = communityMessage {
        communityId = ByteString.copyFrom(groupId.toBytes()); revision = 2
        messageId = ByteString.copyFrom(AccountId.parse("aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee").toBytes())
        sentAt = 1_792_000_000_000; text = "Merhaba topluluk 👋"
    } }

    @Test fun `verify shared Kotlin Swift community signature and content bytes`() {
        val file = fixture()
        // To regenerate explicitly: COMMUNITY_GENERATE_VECTORS=1 ./gradlew :core:test --tests '*CommunityVectorTest*' --rerun-tasks
        if (System.getenv("COMMUNITY_GENERATE_VECTORS") == "1") {
            val state = state()
            val signed = state.sign(owner)
            val vector = buildJsonObject {
                put("version", 1); put("generator", "kotlin-libsignal")
                put("note", "Fixed synthetic test identities; no real accounts or secrets. Signature is randomized and verified, not regenerated byte-for-byte.")
                put("communityId", groupId.toString()); put("ownerAccountId", ownerId.toString()); put("ownerIdentityKey", key)
                put("state", signed.state); put("stateHex", Hex.encode(state.encode())); put("signature", signed.signature)
                put("contentHex", Hex.encode(message().toByteArray())); put("text", message().community.text)
            }
            file.writeText(prettyJson.encodeToString(JsonObject.serializer(), vector) + "\n")
        }
        val vector = Json.parseToJsonElement(file.readText()).jsonObject
        fun string(key: String) = vector.getValue(key).jsonPrimitive.content
        val signed = SignedCommunityState(string("state"), string("signature"))
        assertEquals(state(), signed.verify(string("ownerIdentityKey")))
        assertArrayEquals(state().encode(), Hex.decode(string("stateHex")))
        assertArrayEquals(message().toByteArray(), Hex.decode(string("contentHex")))
        assertEquals(message(), Content.parseFrom(Hex.decode(string("contentHex"))))
    }
}
