#!/usr/bin/env python3
"""The adaptive launcher icon, from the geometry of the iOS app icon (the Android twin of
ios/App/scripts/render-app-icon.swift, which renders AppIcon-1024.png).

The design's app-icon mock (inventory 3.4, element r.2.0) is a 30 × 30 tile with
radial-gradient(90% 90% at 30% 15%, #423a6a → #161826 72%) and the line mark centred: two Ø6
rings (1.5 stroke) joined by an 8 × 1.5 bar, 20 wide, #b5abfc. On Android the tile becomes the
72 dp visible part of the 108 dp adaptive layers (18 dp of overscan on each side), so the mark
keeps its proportion on every launcher mask and stays inside the 66 dp safe zone.

Writes, under app/src/main/res/:
  drawable/ic_launcher_background.xml   the gradient (vector, every density)
  drawable/ic_launcher_foreground.xml   the line mark
  drawable/ic_launcher_monochrome.xml   the line mark for themed icons (Android 13+)
  mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml
  values/ic_launcher_colors.xml
minSdk is 28, so the adaptive icon serves every device; no bitmap mipmaps are needed.

It also renders the tile with Pillow from the same numbers, compares it with the iOS
AppIcon-1024.png, and writes previews (full tile, circle, squircle, themed) and the store
listing's 512 px icon to android/build/launcher-icon/.

Run from anywhere:  python3 android/scripts/render_app_icon.py
                    python3 android/scripts/render_app_icon.py --check   (stale output or a mismatch fails)
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
ANDROID_DIR = SCRIPT_DIR.parent
REPO_DIR = ANDROID_DIR.parent
RES_DIR = ANDROID_DIR / "app" / "src" / "main" / "res"
IOS_ICON = REPO_DIR / "ios" / "App" / "Resources" / "Assets.xcassets" / "AppIcon.appiconset" / "AppIcon-1024.png"
PREVIEW_DIR = ANDROID_DIR / "build" / "launcher-icon"

# The design's tile, in its own 30-unit coordinates (render-app-icon.swift).
TILE = 30.0
GRADIENT_CENTER = (0.30, 0.15)  # fractions of the tile
GRADIENT_RADIUS = 0.90  # fraction of the tile (a circle: the tile is square)
GRADIENT_STOPS = [(0.0, 0x423A6A), (0.72, 0x161826)]
MARK = 0xB5ABFC
RINGS_X = (5.0, 19.0)  # left edge of each ring's 6 × 6 box (border included)
RING_Y = 12.0
RING_SIZE = 6.0
STROKE = 1.5
BAR = (11.0, 15.0 - 0.75, 8.0, 1.5)  # x, y, w, h

# The adaptive icon: 108 dp layers, the tile on the inner 72 dp.
LAYER = 108.0
INSET = 18.0
UNIT = (LAYER - 2 * INSET) / TILE  # dp per tile unit (2.4)

MAX_MEAN_DELTA = 1.5  # mean |Δ| (0–255) allowed against AppIcon-1024.png
HEADER = "<!-- GENERATED by android/scripts/render_app_icon.py from the iOS app icon's geometry. Do not edit by hand. -->"


def hex6(rgb: int) -> str:
    return f"#FF{rgb:06X}"


def fmt(value: float) -> str:
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return text if text != "-0" else "0"


def to_layer(v: float) -> float:
    return INSET + v * UNIT


def ring_path(left: float) -> str:
    """A circle along the middle of the ring's border, as a path (VectorDrawable has no <circle>)."""
    r = (RING_SIZE - STROKE) / 2 * UNIT
    cx = to_layer(left + RING_SIZE / 2)
    cy = to_layer(RING_Y + RING_SIZE / 2)
    return f"M{fmt(cx - r)},{fmt(cy)}a{fmt(r)},{fmt(r)} 0,1 1,{fmt(2 * r)},0a{fmt(r)},{fmt(r)} 0,1 1,{fmt(-2 * r)},0"


def bar_path() -> str:
    x, y, w, h = BAR
    return f"M{fmt(to_layer(x))},{fmt(to_layer(y))}h{fmt(w * UNIT)}v{fmt(h * UNIT)}h{fmt(-w * UNIT)}z"


def mark_vector(ink: str) -> str:
    rings = "\n".join(
        f'    <path\n        android:pathData="{ring_path(x)}"\n        android:strokeColor="{ink}"\n        android:strokeWidth="{fmt(STROKE * UNIT)}" />'
        for x in RINGS_X
    )
    return "\n".join(
        [
            '<?xml version="1.0" encoding="utf-8"?>',
            HEADER,
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            f'    android:width="{fmt(LAYER)}dp"',
            f'    android:height="{fmt(LAYER)}dp"',
            f'    android:viewportWidth="{fmt(LAYER)}"',
            f'    android:viewportHeight="{fmt(LAYER)}">',
            rings,
            "    <path",
            f'        android:pathData="{bar_path()}"',
            f'        android:fillColor="{ink}" />',
            "</vector>",
            "",
        ]
    )


def background_vector() -> str:
    cx = to_layer(GRADIENT_CENTER[0] * TILE)
    cy = to_layer(GRADIENT_CENTER[1] * TILE)
    radius = GRADIENT_RADIUS * TILE * UNIT
    items = "\n".join(
        f'                <item android:offset="{fmt(offset)}" android:color="@color/{name}" />'
        for (offset, _), name in zip(GRADIENT_STOPS, ("ic_launcher_gradient_start", "ic_launcher_background"))
    )
    return "\n".join(
        [
            '<?xml version="1.0" encoding="utf-8"?>',
            HEADER,
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            '    xmlns:aapt="http://schemas.android.com/aapt"',
            f'    android:width="{fmt(LAYER)}dp"',
            f'    android:height="{fmt(LAYER)}dp"',
            f'    android:viewportWidth="{fmt(LAYER)}"',
            f'    android:viewportHeight="{fmt(LAYER)}">',
            "    <!-- radial-gradient(90% 90% at 30% 15%, #423a6a, #161826 72%) over the 72 dp tile; beyond 72 % the end colour. -->",
            "    <path",
            f'        android:pathData="M0,0h{fmt(LAYER)}v{fmt(LAYER)}h-{fmt(LAYER)}z">',
            '        <aapt:attr name="android:fillColor">',
            "            <gradient",
            '                android:type="radial"',
            f'                android:centerX="{fmt(cx)}"',
            f'                android:centerY="{fmt(cy)}"',
            f'                android:gradientRadius="{fmt(radius)}"',
            '                android:tileMode="clamp">',
            items,
            "            </gradient>",
            "        </aapt:attr>",
            "    </path>",
            "</vector>",
            "",
        ]
    )


def adaptive_icon() -> str:
    return "\n".join(
        [
            '<?xml version="1.0" encoding="utf-8"?>',
            HEADER,
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
            '    <background android:drawable="@drawable/ic_launcher_background" />',
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />',
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />',
            "</adaptive-icon>",
            "",
        ]
    )


def colors() -> str:
    return "\n".join(
        [
            '<?xml version="1.0" encoding="utf-8"?>',
            HEADER,
            "<resources>",
            "    <!-- The app icon's colours (U2FixedColors.appIconTop / appIconBottom / appIconMark). -->",
            f'    <color name="ic_launcher_gradient_start">#{GRADIENT_STOPS[0][1]:06X}</color>',
            f'    <color name="ic_launcher_background">#{GRADIENT_STOPS[1][1]:06X}</color>',
            f'    <color name="ic_launcher_mark">#{MARK:06X}</color>',
            "</resources>",
            "",
        ]
    )


def outputs() -> dict[Path, str]:
    return {
        RES_DIR / "drawable" / "ic_launcher_background.xml": background_vector(),
        RES_DIR / "drawable" / "ic_launcher_foreground.xml": mark_vector("@color/ic_launcher_mark"),
        # Themed icons use only the alpha of this layer; the system picks the colour.
        RES_DIR / "drawable" / "ic_launcher_monochrome.xml": mark_vector("#FF000000"),
        RES_DIR / "mipmap-anydpi-v26" / "ic_launcher.xml": adaptive_icon(),
        RES_DIR / "mipmap-anydpi-v26" / "ic_launcher_round.xml": adaptive_icon(),
        RES_DIR / "values" / "ic_launcher_colors.xml": colors(),
    }


# ---------------------------------------------------------------------------
# Rendering (Pillow), to compare with the iOS icon and to preview the masks


def render_tile(size: int):
    """The tile at size × size px, from the same numbers as the vectors."""
    from PIL import Image, ImageDraw

    scale = size / TILE
    image = Image.new("RGB", (size, size))
    cx, cy = GRADIENT_CENTER[0] * size, GRADIENT_CENTER[1] * size
    radius = GRADIENT_RADIUS * size
    (o0, c0), (o1, c1) = GRADIENT_STOPS
    start = [(c0 >> s) & 0xFF for s in (16, 8, 0)]
    end = [(c1 >> s) & 0xFF for s in (16, 8, 0)]
    pixels = []
    for y in range(size):
        dy = (y + 0.5 - cy) ** 2
        for x in range(size):
            t = math.sqrt((x + 0.5 - cx) ** 2 + dy) / radius
            f = min(1.0, max(0.0, (t - o0) / (o1 - o0)))
            pixels.append(tuple(round(a + (b - a) * f) for a, b in zip(start, end)))
    image.putdata(pixels)

    ss = 4  # supersampled mark
    mark = Image.new("L", (size * ss, size * ss), 0)
    draw = ImageDraw.Draw(mark)
    unit = scale * ss
    for x in RINGS_X:
        box = [x * unit, RING_Y * unit, (x + RING_SIZE) * unit, (RING_Y + RING_SIZE) * unit]
        draw.ellipse(box, outline=255, width=round(STROKE * unit))
    bx, by, bw, bh = BAR
    draw.rectangle([bx * unit, by * unit, (bx + bw) * unit - 1, (by + bh) * unit - 1], fill=255)
    mask = mark.resize((size, size), Image.LANCZOS)
    ink = Image.new("RGB", (size, size), tuple((MARK >> s) & 0xFF for s in (16, 8, 0)))
    image.paste(ink, (0, 0), mask)
    return image, mask


def compare_with_ios() -> float:
    from PIL import Image

    reference = Image.open(IOS_ICON).convert("RGB")
    rendered, _ = render_tile(reference.width)
    a = reference.tobytes()
    b = rendered.tobytes()
    return sum(abs(x - y) for x, y in zip(a, b)) / len(a)


def write_previews() -> None:
    """Full tile, the round and squircle launcher masks over the 108 dp layer, and the themed icon."""
    from PIL import Image, ImageDraw

    PREVIEW_DIR.mkdir(parents=True, exist_ok=True)
    tile, mark = render_tile(432)  # 72 dp at 6 px/dp
    tile.save(PREVIEW_DIR / "tile-432.png")
    # The store listing's 512 × 512 icon (uploaded by hand; the store applies its own mask).
    render_tile(512)[0].save(PREVIEW_DIR / "playstore-512.png")
    layer = int(LAYER * 6)
    inset = int(INSET * 6)
    # The layer: the gradient continues into the overscan (approximated by the tile's edge colours).
    full = Image.new("RGB", (layer, layer), tuple((GRADIENT_STOPS[1][1] >> s) & 0xFF for s in (16, 8, 0)))
    full.paste(tile, (inset, inset))
    for name, shape in (("round", "circle"), ("squircle", "rounded")):
        m = Image.new("L", (layer, layer), 0)
        d = ImageDraw.Draw(m)
        box = [inset, inset, layer - inset - 1, layer - inset - 1]
        if shape == "circle":
            d.ellipse(box, fill=255)
        else:
            d.rounded_rectangle(box, radius=int(72 * 6 * 0.3), fill=255)
        out = Image.new("RGBA", (layer, layer), (0, 0, 0, 0))
        out.paste(full, (0, 0), m)
        out.crop((inset, inset, layer - inset, layer - inset)).save(PREVIEW_DIR / f"launcher-{name}.png")
    themed = Image.new("RGB", (432, 432), (0xE8, 0xDE, 0xF8))
    themed.paste(Image.new("RGB", (432, 432), (0x4A, 0x44, 0x58)), (0, 0), mark)
    themed.save(PREVIEW_DIR / "launcher-themed.png")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if an output is stale or the geometry no longer matches AppIcon-1024.png")
    parser.add_argument("--no-compare", action="store_true", help="skip the Pillow render and the comparison with the iOS icon")
    args = parser.parse_args()
    files = outputs()
    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ANDROID_DIR)}", file=sys.stderr)
        if stale:
            sys.exit(1)
    else:
        for path, text in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ANDROID_DIR)}")
    if not args.no_compare:
        delta = compare_with_ios()
        print(f"tile vs AppIcon-1024.png: mean |Δ| {delta:.2f} (limit {MAX_MEAN_DELTA})")
        if delta > MAX_MEAN_DELTA:
            print("error: the geometry no longer matches the iOS icon", file=sys.stderr)
            sys.exit(1)
        if not args.check:
            write_previews()
            print(f"previews in {PREVIEW_DIR.relative_to(ANDROID_DIR)}")
    if args.check:
        print("launcher icon is up to date")


if __name__ == "__main__":
    main()
