#!/usr/bin/env python3
"""Bundles exactly the Phosphor 2.1.1 glyphs listed in ios/design/icons.md (the Android twin of
ios/App/scripts/generate-icons.py), plus the two invite channel glyphs of Invite.xcassets.

Reads  ios/design/icons/phosphor/{regular,fill}/<name>.svg
       ios/App/Sources/Features/Invite/Invite.xcassets/ph-<name>.imageset/ph-<name>.svg
writes designsystem/src/main/kotlin/com/syconx/us2us/ui/icons/PhosphorGlyph.gen.kt:
the typed list of glyphs with their SVG path data on Phosphor's 256-unit grid. PhosphorIcon
turns them into vectors and tints them at draw time.

Run from anywhere:  python3 android/scripts/generate_icons.py
                    python3 android/scripts/generate_icons.py --check   (fails if the output is stale)
The output is committed; re-run after the design's icon list changes.
"""

from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
ANDROID_DIR = SCRIPT_DIR.parent
REPO_DIR = ANDROID_DIR.parent
PHOSPHOR = REPO_DIR / "ios" / "design" / "icons" / "phosphor"
INVITE_ASSETS = REPO_DIR / "ios" / "App" / "Sources" / "Features" / "Invite" / "Invite.xcassets"
OUT = ANDROID_DIR / "designsystem" / "src" / "main" / "kotlin" / "com" / "syconx" / "us2us" / "ui" / "icons" / "PhosphorGlyph.gen.kt"

SVG_NS = "{http://www.w3.org/2000/svg}"
WEIGHTS = ("regular", "fill")


class IconError(Exception):
    pass


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("-"))


def path_data(svg: Path) -> str:
    """The single path of a Phosphor SVG, after checking it is drawn the way PhosphorIcon draws it."""
    root = ET.fromstring(svg.read_text(encoding="utf-8"))
    if root.tag != SVG_NS + "svg":
        raise IconError(f"{svg}: not an SVG")
    if root.get("viewBox") != "0 0 256 256":
        raise IconError(f"{svg}: viewBox {root.get('viewBox')!r}, expected '0 0 256 256'")
    if root.get("fill") not in ("currentColor", "#000000", None):
        raise IconError(f"{svg}: fill {root.get('fill')!r}")
    children = list(root)
    if len(children) != 1 or children[0].tag != SVG_NS + "path":
        raise IconError(f"{svg}: expected exactly one <path>, found {[c.tag for c in children]}")
    path = children[0]
    extra = set(path.attrib) - {"d"}
    if extra:
        raise IconError(f"{svg}: unsupported path attributes {sorted(extra)} (fill-rule, transform …)")
    d = path.get("d", "").strip()
    if not d or not re.fullmatch(r"[MmLlHhVvCcSsQqTtAaZz0-9eE.,\s+-]+", d):
        raise IconError(f"{svg}: unexpected path data")
    return d


def collect() -> dict[str, dict[str, tuple[str, str]]]:
    """name → weight → (path data, source relative to the repository)."""
    glyphs: dict[str, dict[str, tuple[str, str]]] = {}
    for weight in WEIGHTS:
        for svg in sorted((PHOSPHOR / weight).glob("*.svg")):
            glyphs.setdefault(svg.stem, {})[weight] = (path_data(svg), str(svg.relative_to(REPO_DIR)))
    for imageset in sorted(INVITE_ASSETS.glob("ph-*.imageset")):
        name = imageset.name[len("ph-") : -len(".imageset")]
        svg = imageset / f"ph-{name}.svg"
        if name in glyphs:
            raise IconError(f"{svg}: {name} is already a design glyph")
        glyphs[name] = {"regular": (path_data(svg), str(svg.relative_to(REPO_DIR)))}
    if not glyphs:
        raise IconError("no glyphs found")
    return glyphs


def kotlin_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def kotlin_file(glyphs: dict[str, dict[str, tuple[str, str]]]) -> str:
    total = sum(len(w) for w in glyphs.values())
    lines = [
        "// GENERATED by android/scripts/generate_icons.py from ios/design/icons/phosphor and Invite.xcassets.",
        "// Do not edit by hand: change the design's icon list and re-run the script.",
        "",
        "package com.syconx.us2us.ui.icons",
        "",
        "/**",
        " * The Phosphor 2.1.1 glyphs the design uses (ios/design/icons.md), and only those, plus the invite",
        " * channel glyphs (`envelope-simple`, `whatsapp-logo`). Each carries the SVG path data of the weights",
        f" * it is bundled in, on Phosphor's 256-unit grid ({len(glyphs)} glyphs, {total} glyph/weight combinations).",
        " */",
        "enum class PhosphorGlyph(",
        "    /** The Phosphor name: `ghost`, `x-circle`. */",
        "    val raw: String,",
        "    /** The regular weight's path data, or null when the design uses only the fill. */",
        "    internal val regularPath: String?,",
        "    /** The fill weight's path data, or null when the design uses only the regular. */",
        "    internal val fillPath: String?,",
        ") {",
    ]
    for name in sorted(glyphs):
        weights = glyphs[name]
        regular = kotlin_string(weights["regular"][0]) if "regular" in weights else "null"
        fill = kotlin_string(weights["fill"][0]) if "fill" in weights else "null"
        sources = ", ".join(src for _, src in (weights[w] for w in WEIGHTS if w in weights))
        lines.append(f"    /** `{name}` — {sources} */")
        lines.append(f"    {pascal(name)}(")
        lines.append(f"        {kotlin_string(name)},")
        lines.append(f"        {regular},")
        lines.append(f"        {fill},")
        lines.append("    ),")
    lines += [
        "    ;",
        "",
        "    /** The weights bundled for this glyph. */",
        "    val availableWeights: Set<PhosphorWeight>",
        "        get() = when {",
        "            regularPath != null && fillPath != null -> setOf(PhosphorWeight.Regular, PhosphorWeight.Fill)",
        "            fillPath != null -> setOf(PhosphorWeight.Fill)",
        "            else -> setOf(PhosphorWeight.Regular)",
        "        }",
        "",
        "    /** The asset name the iOS app uses: `ph-<name>` or `ph-<name>-fill`. */",
        '    fun assetName(weight: PhosphorWeight): String = if (weight == PhosphorWeight.Fill) "ph-$raw-fill" else "ph-$raw"',
        "",
        "    companion object {",
        "        /** The glyph named [raw] (`x-circle`), or null. */",
        "        fun fromRaw(raw: String): PhosphorGlyph? = entries.firstOrNull { it.raw == raw }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated file differs from the SVGs")
    args = parser.parse_args()
    try:
        glyphs = collect()
    except IconError as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
    text = kotlin_file(glyphs)
    total = sum(len(w) for w in glyphs.values())
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"stale: {OUT.relative_to(ANDROID_DIR)}", file=sys.stderr)
            sys.exit(1)
        print(f"icons are up to date ({len(glyphs)} glyphs, {total} glyph/weight combinations)")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ANDROID_DIR)} ({len(glyphs)} glyphs, {total} glyph/weight combinations)")


if __name__ == "__main__":
    main()
