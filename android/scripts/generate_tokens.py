# ---------------------------------------------------------------------------
# Values


def parse_color(value: str) -> tuple[int, float]:
    """'#e9e9ed' or '#e9e9ed@16%' → (0xe9e9ed, 0.16)."""
    m = re.fullmatch(r"#([0-9a-fA-F]{6})(?:@(\d+(?:\.\d+)?)%)?", value.strip())
    if not m:
        raise ValueError(f"unsupported colour value: {value!r}")
    alpha = float(m.group(2)) / 100 if m.group(2) else 1.0
    return int(m.group(1), 16), alpha


def is_color(value: str) -> bool:
    return re.fullmatch(r"#([0-9a-fA-F]{6})(?:@(\d+(?:\.\d+)?)%)?", value.strip()) is not None


def kt_float(x: float) -> str:
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    if s in ("-0", ""):
        s = "0"
    return s + "f"


def kt_dp(x: float) -> str:
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return f"{s}.dp"


def themed(dark: tuple[int, float], light: tuple[int, float]) -> str:
    return (
        f"U2ThemedColor(dark = 0x{dark[0]:06x}, darkAlpha = {kt_float(dark[1])}, "
        f"light = 0x{light[0]:06x}, lightAlpha = {kt_float(light[1])})"
    )


def argb(rgb: int, alpha: float) -> str:
    # Compose's Color(…, alpha) rounds half up: (alpha · 255 + 0.5).toInt().
    a = int(alpha * 255 + 0.5)
    return f"Color(0x{a:02X}{rgb:06X})"


def doc(text: str) -> str:
    return text.replace("*/", "* /")


def mix(a: int, b: int, t: float) -> int:
    """sRGB mix: `t` of `a`, the rest `b` (CSS color-mix in srgb, rounded)."""
    out = 0
    for shift in (16, 8, 0):
        ca = (a >> shift) & 0xFF
        cb = (b >> shift) & 0xFF
        out |= int(round(ca * t + cb * (1 - t))) << shift
    return out


