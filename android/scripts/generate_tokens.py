def generate_type(tokens: dict) -> str:
    styles = tokens["typography"]["styles"]
    lines = [HEADER, f"package {PACKAGE}", ""]
    lines.append("/**")
    lines.append(" * The design's type styles, mirrored 1:1 from `tokens.json › typography.styles`.")
    lines.append(" * Every text in the design maps to exactly one of these (tokens.md › Typography).")
    lines.append(" * `displayPunctuation` is not a standalone style: see [U2TextStyle.punctuation].")
    lines.append(" */")
    lines.append("object U2TextStyles {")
    names = []
    for name, v in styles.items():
        if name == "displayPunctuation":
            continue
        o = STYLE_OVERRIDES.get(name, {})
        family = FAMILY[v["family"]]
        uppercase = v.get("textCase") == "uppercase"
        tnum = bool(v.get("monospacedDigits"))
        italic = bool(o.get("italic", False))
        fixed = v["family"] == "Doto" or name.startswith("avatarInitial") or name in FIXED_SIZE_STYLES
        screens = ", ".join(v.get("screens", []))
        desc = f"{v['family']} {v['weight']} {kt_float(v['size'])[:-1]}/{kt_float(v['lineHeight'])[:-1]}"
        if v["family"] == "Doto":
            desc += " · ROND 100"
        if v.get("letterSpacing"):
            desc += f" · tracking {kt_float(v['letterSpacing'])[:-1]}"
        if uppercase:
            desc += " · UPPERCASE"
        if tnum:
            desc += " · tnum"
        if italic:
            desc += " · italic"
        example = (v.get("example") or "").replace("\n", " ")
        lines.append(f"    /** {doc(desc)} — e.g. “{doc(example)}” ({screens}) */")
        lines.append(
            f"    val {name} = U2TextStyle(\n"
            f"        name = \"{name}\", family = {family}, weight = {v['weight']},\n"
            f"        size = {kt_float(v['size'])}, lineHeight = {kt_float(v['lineHeight'])}, "
            f"tracking = {kt_float(v.get('letterSpacing') or 0)},\n"
            f"        uppercase = {str(uppercase).lower()}, monospacedDigits = {str(tnum).lower()}, "
            f"italic = {str(italic).lower()}, scalesWithFontSize = {str(not fixed).lower()},\n"
            f"    )"
        )
        names.append(name)
    lines.append("")
    lines.append("    /** All styles, in tokens.json order. */")
    lines.append("    val all: List<U2TextStyle> by lazy {")
    lines.append("        listOf(")
    for n in names:
        lines.append(f"            {n},")
    lines.append("        )")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


