def outputs(tokens: dict) -> dict[Path, str]:
    return {
        OUT_DIR / "U2ColorTokens.gen.kt": generate_colors(tokens),
        OUT_DIR / "U2TextStyles.gen.kt": generate_type(tokens),
        OUT_DIR / "U2Metrics.gen.kt": generate_metrics(tokens),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a generated file differs from tokens.json")
    args = parser.parse_args()

    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    files = outputs(tokens)
    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            for p in stale:
                print(f"stale: {p}", file=sys.stderr)
            sys.exit(1)
        print("generated tokens are up to date")
        return
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ANDROID_DIR)}")


if __name__ == "__main__":
    main()
