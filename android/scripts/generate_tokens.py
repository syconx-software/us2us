def size_entries(size: dict) -> list[tuple[str, str, str]]:
    """(name, Kotlin type, Kotlin value) for every size token."""
    out = []
    for key, value in size.items():
        if key == "screen":
            out.append(("designScreen", "DpSize", f"DpSize({kt_dp(value['w'])}, {kt_dp(value['h'])})"))
            continue
        items = value.items() if isinstance(value, dict) else [(None, value)]
        for sub, v in items:
            path = f"{key}.{sub}" if sub else key
            name = SIZE_NAMES.get(path) or (key + sub[0].upper() + sub[1:] if sub else key)
            if isinstance(v, str):
                m = re.fullmatch(r"(\d+(?:\.\d+)?)×(\d+(?:\.\d+)?)", v)
                if not m:
                    raise ValueError(f"size {path}: {v!r}")
                out.append((name, "DpSize", f"DpSize({kt_dp(float(m.group(1)))}, {kt_dp(float(m.group(2)))})"))
            else:
                out.append((name, "Dp", kt_dp(v)))
    return out


def shadow_color(spec: str, base: dict, semantic: dict) -> tuple[tuple[int, float], tuple[int, float]]:
    """A shadow colour in token form → (dark, light) as (rgb, alpha).

    Forms: `accent·70%`, `text·10%`, `accent800`, `bg`, `divider`, `#000@35%`, `#9184d9@70%`, `#f5f4ff`.
    """
    spec = spec.strip()
    m = re.fullmatch(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})(?:@(\d+(?:\.\d+)?)%)?", spec)
    if m:
        hexv = m.group(1)
        if len(hexv) == 3:
            hexv = "".join(c * 2 for c in hexv)
        rgb = int(hexv, 16)
        alpha = float(m.group(2)) / 100 if m.group(2) else 1.0
        return (rgb, alpha), (rgb, alpha)
    m = re.fullmatch(r"([a-zA-Z0-9]+)(?:·(\d+(?:\.\d+)?)%)?", spec)
    if m:
        ref = m.group(1)
        factor = float(m.group(2)) / 100 if m.group(2) else 1.0
        entry = base.get(ref) or semantic.get(ref)
        if entry is None:
            raise ValueError(f"shadow colour {spec!r}: unknown token {ref}")
        d = parse_color(entry["dark"])
        l = parse_color(entry["light"])
        return (d[0], d[1] * factor), (l[0], l[1] * factor)
    raise ValueError(f"shadow colour {spec!r}")


def split_layers(css: str) -> list[str]:
    return [p.strip() for p in css.split(",") if p.strip()]


def parse_layer(layer: str, base: dict, semantic: dict) -> dict:
    """`inset 0 0 0 1.5px accent` / `0 20px 50px -20px accent·60%` → the layer's fields."""
    inset = layer.startswith("inset ")
    if inset:
        layer = layer[len("inset "):]
    parts = layer.split()
    numbers = []
    while parts and re.fullmatch(r"-?\d+(?:\.\d+)?(?:px)?", parts[0]):
        numbers.append(float(parts.pop(0).replace("px", "")))
    x, y, blur, spread = (numbers + [0, 0, 0, 0])[:4]
    dark, light = shadow_color(" ".join(parts), base, semantic)
    return {"inset": inset, "x": x, "y": y, "blur": blur, "spread": spread, "dark": dark, "light": light}


def layer_literal(layer: dict) -> str:
    return (
        f"U2ShadowLayer(inset = {str(layer['inset']).lower()}, x = {kt_dp(layer['x'])}, y = {kt_dp(layer['y'])}, "
        f"blur = {kt_dp(layer['blur'])}, spread = {kt_dp(layer['spread'])}, color = {themed(layer['dark'], layer['light'])})"
    )


def themed_layers(dark_css: str, light_css: str, base: dict, semantic: dict) -> list[str]:
    """shadowSm/Md/Lg: the same geometry with a dark and a light colour per layer."""
    out = []
    dark_layers, light_layers = split_layers(dark_css), split_layers(light_css)
    if len(dark_layers) != len(light_layers):
        raise ValueError(f"shadow {dark_css!r} / {light_css!r}: different layer counts")
    for d, l in zip(dark_layers, light_layers):
        dl = parse_layer(d, base, semantic)
        ll = parse_layer(l, base, semantic)
        for key in ("inset", "x", "y", "blur", "spread"):
            if dl[key] != ll[key]:
                raise ValueError(f"shadow {dark_css!r} / {light_css!r}: {key} differs between the themes")
        out.append(layer_literal({**dl, "light": ll["light"]}))
    return out


def shadow_entries(shadow: dict, base: dict, semantic: dict) -> list[tuple[str, str, list[str], bool]]:
    """(name, css, layers, isFilter) for every shadow token."""

    def layers(css: str) -> list[str]:
        return [layer_literal(parse_layer(layer, base, semantic)) for layer in split_layers(css)]

    out = []
    for name, entry in shadow.items():
        if name == "note":
            continue
        css = entry.get("css", "")
        if "dark" in entry:
            out.append((name, f"dark {entry['dark']} · light {entry['light']}", themed_layers(entry["dark"], entry["light"], base, semantic), False))
        elif name == "ringAccent":
            # `inset 0 0 0 1px accent800 | accent700` — tiles use 800, the self avatar 700.
            out.append(("ringAccent", "inset 0 0 0 1px accent800", layers("inset 0 0 0 1px accent800"), False))
            out.append(("ringAccentSelf", "inset 0 0 0 1px accent700", layers("inset 0 0 0 1px accent700"), False))
        elif name == "cutoutRing":
            # `0 0 0 3px bg (list) / 2px bg (header) / 2.5px bg (reaction chip)`.
            for suffix, width in (("List", 3), ("Header", 2), ("ReactionChip", 2.5)):
                layer = f"0 0 0 {width}px bg"
                out.append((name + suffix, layer, layers(layer), False))
        elif css.startswith("drop-shadow("):
            out.append((name, css, layers(css[len("drop-shadow("):-1]), True))
        else:
            out.append((name, css, layers(css), False))
    return out


def blur_entries(blur: dict) -> list[tuple[str, str, float]]:
    out = []
    for name, entry in blur.items():
        if name == "note":
            continue
        m = re.search(r"blur\((\d+(?:\.\d+)?)px\)", entry["css"])
        out.append((name, entry["css"], float(m.group(1))))
    return out


def scene_palette(name: str, palette: dict) -> list[str]:
    fields = []
    for key, value in palette.items():
        if isinstance(value, str) and is_color(value):
            rgb, alpha = parse_color(value)
            fields.append(f"{key} = {argb(rgb, alpha)}")
        elif isinstance(value, (int, float)):
            fields.append(f"{key} = {kt_float(value)}")
        elif key == "blending":
            fields.append(f"additiveBlending = {str(value == 'additive').lower()}")
        else:
            raise ValueError(f"scene3D.palette.{name}.{key}: {value!r}")
    return [f"    val {name}: U2ScenePalette = U2ScenePalette(", *[f"        {f}," for f in fields], "    )"]


def generate_metrics(tokens: dict) -> str:
    base = tokens["color"]["base"]
    semantic = tokens["color"]["semantic"]
    lines = [HEADER, f"package {PACKAGE}", ""]
    lines += [
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.Dp",
        "import androidx.compose.ui.unit.DpSize",
        "import androidx.compose.ui.unit.dp",
        "",
    ]

    spacing = tokens["spacing"]
    lines.append("/** Spacing used by the design (`tokens.json › spacing`), in dp = design points. */")
    lines.append("object U2Spacing {")
    for name, v in spacing["named"].items():
        lines.append(f"    val {name}: Dp = {kt_dp(v)}")
    lines.append("")
    lines.append("    /** Every padding, gap and margin that occurs in the design. */")
    lines.append("    val scale: List<Dp> by lazy { listOf(" + ", ".join(kt_dp(v) for v in spacing["values"]) + ") }")
    lines.append("}")
    lines.append("")

    radius = tokens["radius"]
    lines.append("/**")
    lines.append(" * Corner radii (`tokens.json › radius`). Rounded rectangles are continuous-corner on iOS;")
    lines.append(" * `pill` (height / 2) is a CircleShape / RoundedCornerShape(50 %).")
    lines.append(" */")
    lines.append("object U2Radius {")
    for name, v in radius["named"].items():
        if isinstance(v, (int, float)):
            lines.append(f"    val {name}: Dp = {kt_dp(v)}")
    lines.append("")
    lines.append("    /** Every radius that occurs in the design. */")
    lines.append("    val scale: List<Dp> by lazy { listOf(" + ", ".join(kt_dp(v) for v in radius["values"]) + ") }")
    lines.append("}")
    lines.append("")

    lines.append("/** Component sizes (`tokens.json › size`), named as in the iOS app. */")
    lines.append("object U2Size {")
    for name, kind, value in size_entries(tokens["size"]):
        lines.append(f"    val {name}: {kind} = {value}")
    lines.append("}")
    lines.append("")

    lines.append("/** Opacity tokens (`tokens.json › opacity`). */")
    lines.append("object U2Opacity {")
    for name, v in tokens["opacity"].items():
        lines.append(f"    const val {name}: Float = {kt_float(v)}")
    lines.append("}")
    lines.append("")

    lines.append("/**")
    lines.append(" * Blur radii (`tokens.json › blur`): the CSS `blur(N)` value, a Gaussian standard deviation")
    lines.append(" * in design points. `U2Effects` converts it for RenderEffect.")
    lines.append(" */")
    lines.append("object U2Blur {")
    for name, css, value in blur_entries(tokens["blur"]):
        lines.append(f"    /** `{doc(css)}` */")
        lines.append(f"    val {name}: Dp = {kt_dp(value)}")
    lines.append("}")
    lines.append("")

    lines.append("/**")
    lines.append(" * Shadows and glows (`tokens.json › shadow`) as data: CSS box-shadow layers in the order CSS")
    lines.append(" * lists them (the first is painted on top). `U2Effects` draws them with CSS semantics.")
    lines.append(" */")
    lines.append("object U2ShadowTokens {")
    for name, css, layers, is_filter in shadow_entries(tokens["shadow"], base, semantic):
        lines.append(f"    /** `{doc(css)}` */")
        lines.append(f"    val {name} = U2ShadowToken(")
        lines.append(f"        name = \"{name}\",")
        lines.append("        layers = listOf(")
        for layer in layers:
            lines.append(f"            {layer},")
        lines.append("        ),")
