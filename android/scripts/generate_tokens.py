# Colours


def semantic_value(name: str, entry: dict, base: dict, theme: str) -> tuple[int, float]:
    """The alias's value computed from its definition (ref · opacity, or color-mix)."""
    if "ref" in entry:
        rgb, alpha = parse_color(base[entry["ref"]][theme])
        return rgb, alpha * float(entry["opacity"])
    css = entry.get("css", "")
    m = re.fullmatch(r"color-mix\(in srgb, var\(--color-([a-z0-9-]+)\) (\d+)%, (#[0-9a-fA-F]{6})\)", css)
    if m:
        ref = re.sub(r"-(\w)", lambda g: g.group(1).upper(), m.group(1))
        rgb, _ = parse_color(base[ref][theme])
        other, _ = parse_color(m.group(3))
        return mix(rgb, other, int(m.group(2)) / 100), 1.0
    raise ValueError(f"semantic colour {name}: no ref and no colour-mix ({css!r})")


def check_semantic(name: str, entry: dict, base: dict) -> None:
    for theme in ("dark", "light"):
        computed = semantic_value(name, entry, base, theme)
        declared = parse_color(entry[theme])
        if computed[0] != declared[0] or abs(computed[1] - declared[1]) > 0.001:
            raise SystemExit(
                f"tokens.json › color.semantic.{name}.{theme}: declared {entry[theme]} but the "
                f"definition gives #{computed[0]:06x}@{computed[1] * 100:g}%"
            )


def fixed_colors(fixed: dict) -> list[tuple[str, int, float, str]]:
    out = []
    for name, entry in fixed.items():
        value = entry["value"]
        if is_color(value):
            rgb, alpha = parse_color(value)
            out.append((name, rgb, alpha, entry.get("use", "")))
        elif name == "onMediaGlass":
            # “#0c0d16@40–55%”: the base; the alpha is chosen where it is drawn.
            rgb = int(re.match(r"#([0-9a-fA-F]{6})", value).group(1), 16)
            out.append(("onMediaGlassBase", rgb, 1.0, entry.get("use", "") + " — base; alpha 40/45/55 % where drawn"))
    return out


def generate_colors(tokens: dict) -> str:
    base = tokens["color"]["base"]
    # Aliases that repeat a base token (`divider`) are emitted once.
    semantic = {k: v for k, v in tokens["color"]["semantic"].items() if k not in base}
    for name, entry in tokens["color"]["semantic"].items():
        check_semantic(name, entry, base)
    fixed = fixed_colors(tokens["color"]["fixed"])

    lines = [HEADER, f"package {PACKAGE}", "", "import androidx.compose.runtime.Immutable", "import androidx.compose.ui.graphics.Color", ""]

    lines.append("/** Theme-dependent colour values, mirrored 1:1 from `tokens.json › color`. */")
    lines.append("object U2ColorTokens {")
    lines.append("    // Base tokens (`color.base`).")
    for name, v in base.items():
        note = v.get("note")
        lines.append(f"    /** `{v.get('css', '')}` · dark {v['dark']} · light {v['light']}" + (f" — {doc(note)}" if note else "") + " */")
        lines.append(f"    val {name} = {themed(parse_color(v['dark']), parse_color(v['light']))}")
    lines.append("")
    lines.append("    // Semantic aliases (`color.semantic`) — what the screens use.")
    lines.append("    // (`divider` is both a base token and an alias; it is declared once above.)")
    for name, v in semantic.items():
        ref = v.get("ref")
        expr = f"{ref} · {round(v['opacity'] * 100)} %" if ref else v.get("css", "")
        lines.append(f"    /** {doc(expr)} — {doc(v.get('use', ''))} */")
        dark = semantic_value(name, v, base, "dark")
        light = semantic_value(name, v, base, "light")
        lines.append(f"    val {name} = {themed(dark, light)}")
    lines.append("")
    lines.append("    /** Every token by name — the token tests compare it with tokens.json. */")
    lines.append("    val all: Map<String, U2ThemedColor> by lazy {")
    lines.append("        mapOf(")
    for name in list(base.keys()) + list(semantic.keys()):
        lines.append(f"            \"{name}\" to {name},")
    lines.append("        )")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("/** Theme-independent colours (`tokens.json › color.fixed`, the entries with a single colour value). */")
    lines.append("object U2FixedColors {")
    for name, rgb, alpha, use in fixed:
        lines.append(f"    /** #{rgb:06x}" + (f"@{round(alpha * 100)}%" if alpha != 1 else "") + f" — {doc(use)} */")
        lines.append(f"    val {name}: Color = {argb(rgb, alpha)}")
    lines.append("}")
    lines.append("")

    all_names = list(base.keys()) + list(semantic.keys())
    lines.append("/**")
    lines.append(" * The colours of one theme: every base and semantic token resolved for dark or light,")
    lines.append(" * plus the fixed colours (identical in both). Read it through `U2Theme.colors`.")
    lines.append(" */")
    lines.append("@Immutable")
    lines.append("class U2ColorScheme private constructor(")
    lines.append("    /** True for the dark token set (the design's default). */")
    lines.append("    val isDark: Boolean,")
    for name in all_names:
        lines.append(f"    val {name}: Color,")
    for name, _, _, _ in fixed:
        lines.append(f"    val {name}: Color,")
    lines.append(") {")
    lines.append("    companion object {")
    lines.append("        /** The dark theme (default). */")
    lines.append("        val Dark: U2ColorScheme = resolve(dark = true)")
    lines.append("        /** The light theme (8.x). */")
    lines.append("        val Light: U2ColorScheme = resolve(dark = false)")
    lines.append("")
    lines.append("        private fun resolve(dark: Boolean) = U2ColorScheme(")
    lines.append("            isDark = dark,")
    for name in all_names:
        lines.append(f"            {name} = U2ColorTokens.{name}.resolve(dark),")
    for name, _, _, _ in fixed:
        lines.append(f"            {name} = U2FixedColors.{name},")
    lines.append("        )")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


