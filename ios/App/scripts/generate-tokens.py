#!/usr/bin/env python3
"""Mirrors ios/design/tokens.json 1:1 into Swift.

Writes
  Sources/DesignSystem/Tokens/U2ColorTokens+Generated.swift   base + semantic colours (dark/light)
  Sources/DesignSystem/Tokens/U2TextStyle+Generated.swift     the 91 type styles

Run from anywhere:  python3 ios/App/scripts/generate-tokens.py
(ios/App/scripts/generate.sh --tokens runs it too). The output is committed;
never edit the generated files by hand — change tokens.json and re-run.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
APP_DIR = SCRIPT_DIR.parent
TOKENS = APP_DIR.parent / "design" / "tokens.json"
OUT_DIR = APP_DIR / "Sources" / "DesignSystem" / "Tokens"

HEADER = """// GENERATED by ios/App/scripts/generate-tokens.py from ios/design/tokens.json.
// Do not edit by hand: change tokens.json and re-run the script.
"""

# Styles whose rendering differs from what tokens.json records.
STYLE_OVERRIDES = {
    # inventory 5.2: “Bu mesaj herkesten silindi” is set in Inter 400 *italic*.
    "bubbleTombstone": {"italic": True},
}

# Styles that keep their size under Dynamic Type: brand/display (Doto) moments,
# glyphs inside fixed-size circles, and the keypad (tokens.md › Typography).
FIXED_SIZE_STYLES = {
    "keypadDigit",
    "emojiReactionChip",
    "emojiReactionPicker",
    "badge",
}


def parse_color(value: str) -> tuple[int, float]:
    """'#e9e9ed' or '#e9e9ed@16%' → (0xe9e9ed, 0.16)."""
    m = re.fullmatch(r"#([0-9a-fA-F]{6})(?:@(\d+(?:\.\d+)?)%)?", value.strip())
    if not m:
        raise ValueError(f"unsupported colour value: {value!r}")
    alpha = float(m.group(2)) / 100 if m.group(2) else 1.0
    return int(m.group(1), 16), alpha


def swift_double(x: float) -> str:
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return s if "." in s else s + ".0" if s.isdigit() else s


def alpha_literal(a: float) -> str:
    return "1" if a == 1 else swift_double(a)


def color_entry(name: str, dark: str, light: str) -> str:
    d, da = parse_color(dark)
    l, la = parse_color(light)
    return (
        f"    static let {name} = U2ThemedColor("
        f"dark: 0x{d:06x}, darkAlpha: {alpha_literal(da)}, "
        f"light: 0x{l:06x}, lightAlpha: {alpha_literal(la)})"
    )


def generate_colors(tokens: dict) -> str:
    base = tokens["color"]["base"]
    # Aliases that repeat a base token (e.g. `divider`) are emitted once.
    semantic = {k: v for k, v in tokens["color"]["semantic"].items() if k not in base}

    lines = [HEADER, "import SwiftUI", ""]
    lines.append("/// Theme-dependent colour values, mirrored 1:1 from `tokens.json › color`.")
    lines.append("enum U2ColorTokens {")
    lines.append("    // MARK: Base tokens (`color.base`)")
    for name, v in base.items():
        doc = v.get("css", "")
        note = v.get("note")
        lines.append(f"    /// `{doc}` · dark {v['dark']} · light {v['light']}" + (f" — {note}" if note else ""))
        lines.append(color_entry(name, v["dark"], v["light"]))
    lines.append("")
    lines.append("    // MARK: Semantic aliases (`color.semantic`) — what the screens use")
    lines.append("    // (`divider` is both a base token and an alias; it is declared once above.)")
    for name, v in semantic.items():
        ref = v.get("ref")
        expr = f"{ref} · {round(v['opacity'] * 100)} %" if ref else v.get("css", "")
        use = v.get("use", "")
        lines.append(f"    /// {expr} — {use}".rstrip(" —"))
        lines.append(color_entry(name, v["dark"], v["light"]))
    lines.append("}")
    lines.append("")

    # SwiftUI accessors, cached.
    lines.append("/// Cached SwiftUI colours for every token (`Color.u2.<token>`).")
    lines.append("enum U2ColorCache {")
    for name in list(base.keys()) + list(semantic.keys()):
        lines.append(f"    static let {name} = Color(U2ColorTokens.{name})")
    lines.append("}")
    lines.append("")
    lines.append("extension U2Colors {")
    for name, v in base.items():
        lines.append(f"    /// Base token `{name}` (dark {v['dark']}, light {v['light']}).")
        lines.append(f"    var {name}: Color {{ U2ColorCache.{name} }}")
    for name, v in semantic.items():
        lines.append(f"    /// Semantic alias `{name}` (dark {v['dark']}, light {v['light']}).")
        lines.append(f"    var {name}: Color {{ U2ColorCache.{name} }}")
    lines.append("}")
    lines.append("")
    lines.append("extension U2ColorTokens {")
    lines.append("    /// Every token by name — used by the token tests to compare against tokens.json.")
    lines.append("    static let all: [String: U2ThemedColor] = [")
    for name in list(base.keys()) + list(semantic.keys()):
        lines.append(f"        \"{name}\": {name},")
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


FAMILY = {"Doto": ".doto", "Martian Mono": ".martianMono", "Inter": ".inter"}


def generate_type(tokens: dict) -> str:
    styles = tokens["typography"]["styles"]
    lines = [HEADER, "import Foundation", ""]
    lines.append("/// The design's type styles, mirrored 1:1 from `tokens.json › typography.styles`.")
    lines.append("/// Every text in the design maps to exactly one of these (tokens.md › Typography).")
    lines.append("extension U2TextStyle {")
    names = []
    for name, v in styles.items():
        if name == "displayPunctuation":
            # Not a standalone style: the trailing “.” of a Doto headline is
            # set in Inter 700 at the Doto run's size (see U2DisplayText).
            continue
        o = STYLE_OVERRIDES.get(name, {})
        family = FAMILY[v["family"]]
        uppercase = v.get("textCase") == "uppercase"
        tnum = bool(v.get("monospacedDigits"))
        italic = bool(o.get("italic", False))
        fixed = v["family"] == "Doto" or name.startswith("avatarInitial") or name in FIXED_SIZE_STYLES
        screens = ", ".join(v.get("screens", []))
        desc = f"{v['family']} {v['weight']} {swift_double(v['size'])}/{swift_double(v['lineHeight'])}"
        if v["family"] == "Doto":
            desc += " · ROND 100"
        if v.get("letterSpacing"):
            desc += f" · tracking {swift_double(v['letterSpacing'])}"
        if uppercase:
            desc += " · UPPERCASE"
        if tnum:
            desc += " · tnum"
        if italic:
            desc += " · italic"
        example = (v.get("example") or "").replace("\n", " ")
        lines.append(f"    /// {desc} — e.g. “{example}” ({screens})")
        lines.append(
            f"    static let {name} = U2TextStyle(\n"
            f"        name: \"{name}\", family: {family}, weight: {v['weight']},\n"
            f"        size: {swift_double(v['size'])}, lineHeight: {swift_double(v['lineHeight'])}, "
            f"tracking: {swift_double(v.get('letterSpacing') or 0)},\n"
            f"        uppercase: {str(uppercase).lower()}, monospacedDigits: {str(tnum).lower()}, "
            f"italic: {str(italic).lower()}, scalesWithDynamicType: {str(not fixed).lower()})"
        )
        names.append(name)
    lines.append("")
    lines.append("    /// All styles, in tokens.json order.")
    lines.append("    static let all: [U2TextStyle] = [")
    for n in names:
        lines.append(f"        .{n},")
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "U2ColorTokens+Generated.swift").write_text(generate_colors(tokens), encoding="utf-8")
    (OUT_DIR / "U2TextStyle+Generated.swift").write_text(generate_type(tokens), encoding="utf-8")
    print(f"wrote {OUT_DIR}/U2ColorTokens+Generated.swift and U2TextStyle+Generated.swift")


if __name__ == "__main__":
    main()
