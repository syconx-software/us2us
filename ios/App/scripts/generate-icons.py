#!/usr/bin/env python3
"""Bundles exactly the Phosphor 2.1.1 glyphs listed in ios/design/icons.md.

Copies ios/design/icons/phosphor/{regular,fill}/<name>.svg into
  Resources/Assets.xcassets/Phosphor/ph-<name>[-fill].imageset/
as single-colour template images with preserved vector data, copies the MIT
licence to Resources/Licenses/, and writes
  Sources/DesignSystem/Icons/PhosphorGlyph+Generated.swift
(the typed list of glyphs). The output is committed; re-run after the design's
icon list changes:  python3 ios/App/scripts/generate-icons.py
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
APP_DIR = SCRIPT_DIR.parent
DESIGN_ICONS = APP_DIR.parent / "design" / "icons" / "phosphor"
CATALOG = APP_DIR / "Resources" / "Assets.xcassets" / "Phosphor"
SWIFT_OUT = APP_DIR / "Sources" / "DesignSystem" / "Icons" / "PhosphorGlyph+Generated.swift"
LICENSE_OUT = APP_DIR / "Resources" / "Licenses" / "Phosphor-LICENSE.txt"


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(p.capitalize() for p in rest)


def prepare_svg(text: str) -> str:
    # Asset catalogs rasterise SVGs at build time / render them as vectors;
    # `currentColor` is not understood there. Template rendering recolours the
    # glyph anyway, so paint it opaque black and give it an explicit size.
    text = text.replace('fill="currentColor"', 'fill="#000000"')
    text = re.sub(r"<svg ", '<svg width="256" height="256" ', text, count=1)
    return text


def main() -> None:
    if CATALOG.exists():
        shutil.rmtree(CATALOG)
    CATALOG.mkdir(parents=True)
    (CATALOG / "Contents.json").write_text(
        json.dumps({"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": False}}, indent=2) + "\n"
    )

    glyphs: dict[str, set[str]] = {}
    for weight in ("regular", "fill"):
        for svg in sorted((DESIGN_ICONS / weight).glob("*.svg")):
            name = svg.stem
            glyphs.setdefault(name, set()).add(weight)
            asset = f"ph-{name}" + ("-fill" if weight == "fill" else "")
            folder = CATALOG / f"{asset}.imageset"
            folder.mkdir()
            (folder / f"{asset}.svg").write_text(prepare_svg(svg.read_text()))
            contents = {
                "images": [{"filename": f"{asset}.svg", "idiom": "universal"}],
                "info": {"author": "xcode", "version": 1},
                "properties": {
                    "preserves-vector-representation": True,
                    "template-rendering-intent": "template",
                },
            }
            (folder / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")

    LICENSE_OUT.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(DESIGN_ICONS / "LICENSE", LICENSE_OUT)

    lines = [
        "// GENERATED by ios/App/scripts/generate-icons.py from ios/design/icons/phosphor.",
        "// Do not edit by hand.",
        "",
        "/// The Phosphor 2.1.1 glyphs the design uses (ios/design/icons.md) — and only those.",
        "/// Each is bundled as `ph-<name>` (regular) and, where the design uses it, `ph-<name>-fill`.",
        "enum PhosphorGlyph: String, CaseIterable, Sendable {",
    ]
    for name in sorted(glyphs):
        lines.append(f"    case {camel(name)} = \"{name}\"")
    lines += [
        "",
        "    /// The weights bundled for this glyph.",
        "    var availableWeights: Set<PhosphorWeight> {",
        "        switch self {",
    ]
    both = sorted(n for n, w in glyphs.items() if w == {"regular", "fill"})
    fill_only = sorted(n for n, w in glyphs.items() if w == {"fill"})
    if both:
        lines.append("        case " + ", ".join("." + camel(n) for n in both) + ":")
        lines.append("            [.regular, .fill]")
    if fill_only:
        lines.append("        case " + ", ".join("." + camel(n) for n in fill_only) + ":")
        lines.append("            [.fill]")
    lines += [
        "        default:",
        "            [.regular]",
        "        }",
        "    }",
        "}",
        "",
    ]
    SWIFT_OUT.parent.mkdir(parents=True, exist_ok=True)
    SWIFT_OUT.write_text("\n".join(lines))
    total = sum(len(w) for w in glyphs.values())
    print(f"bundled {total} glyph/weight assets ({len(glyphs)} glyphs) into {CATALOG}")


if __name__ == "__main__":
    main()
